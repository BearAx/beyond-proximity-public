def test_view_selection_compares_strategies_and_reduces_large_k(tmp_path):
    scene = tmp_path / "scene"
    frames = []
    for index in range(5):
        matrix = [row[:] for row in IDENTITY]
        matrix[0][3] = float(index)
        frames.append({
            "view_id": f"v{index + 1:03d}",
            "file_path": f"images/v{index + 1:03d}.png",
            "transform_matrix": matrix,
        })
    _write_json(scene / "transforms.json", {
        "fl_x": 1.0,
        "fl_y": 1.0,
        "cx": 1.0,
        "cy": 1.0,
        "w": 2,
        "h": 2,
        "frames": frames,
    })

    report = select_views(scene, k_values=[3, 10], seed=7)

    assert report["candidate_view_count"] == 5
    assert report["results"][0]["effective_k"] == 3
    assert report["results"][1]["effective_k"] == 5
    assert report["results"][1]["coverage_greedy"]["coverage_ratio"] == 1.0
    assert report["results"][1]["random"]["coverage_ratio"] == 1.0
    assert report["results"][1]["trajectory"]["coverage_ratio"] == 1.0
    assert any("Requested K=10" in warning for warning in report["warnings"])


def test_view_selection_reports_zero_candidates_without_fabricated_coverage(tmp_path):
    scene = tmp_path / "ConferenceHall"
    _ply(scene / "geometry" / "scene.ply")

    report = select_views(scene, k_values=[10, 20, 50, 100], seed=7)

    assert report["layout"] == "ply_backend"
    assert report["candidate_view_count"] == 0
    assert report["comparison_available"] is False
    assert report["coverage_proxy"]["status"] == "not_available"
    assert report["coverage_statistics"]["effective_k_values"] == [0, 0, 0, 0]
    assert report["coverage_statistics"]["comparison_run_count"] == 0
    assert len(report["results"]) == 4
    for row in report["results"]:
        assert row["effective_k"] == 0
        assert row["comparison_status"] == "not_available"
        for strategy in ("coverage_greedy", "random", "trajectory"):
            assert row[strategy]["status"] == "not_available"
            assert row[strategy]["coverage_ratio"] is None
            assert row[strategy]["selected_view_ids"] == []
    for requested_k in (10, 20, 50, 100):
        assert any(f"Requested K={requested_k}" in warning for warning in report["warnings"])
